def is_pokemon_fully_evolved(pid: int, gen: int) -> bool:
    """Returns True if the Pokémon with `pid` is fully evolved in generation `gen`."""
    if pid in LATER_EVOLUTIONS:
        return gen < LATER_EVOLUTIONS[pid]
    return pid not in NOT_FULLY_EVOLVED

